/// Lucide 图标 Shape（可直接 .stroke / .fill）。
struct LucideShape: Shape {
    let icon: Lucide
    func path(in rect: CGRect) -> Path { icon.path(in: rect) }
}

/// Lucide 图标视图：24x24 网格、1.5px 细线、圆头圆角，跟随 color 着色。
///
/// - filled: true 时填充（如收藏激活填红），false 时仅描边。
struct LucideIcon: View {
    let icon: Lucide
    var size: CGFloat = 22
    var color: Color = .primary
    var filled: Bool = false
    private var lineWidth: CGFloat { size / 24 * 1.5 }
    var body: some View {
        LucideShape(icon: icon)
            .stroke(color, style: StrokeStyle(lineWidth: lineWidth, lineCap: .round, lineJoin: .round))
            .frame(width: size, height: size)
            .overlay(
                filled
                    ? AnyView(LucideShape(icon: icon).fill(color).frame(width: size, height: size))
                    : AnyView(EmptyView())
            )
    }
}

