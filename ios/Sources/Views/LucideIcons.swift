/// 24x24 网格 → 实际 rect 的换算器（所有图标共用，构图一致）。
private struct LucideGrid {
    let rect: CGRect
    func p(_ gx: CGFloat, _ gy: CGFloat) -> CGPoint {
        CGPoint(x: rect.minX + gx * rect.width / 24,
               y: rect.minY + gy * rect.height / 24)
    }
    /// 椭圆（cx,cy,r 均为 24 网格坐标）。
    func e(_ cx: CGFloat, _ cy: CGFloat, _ r: CGFloat) -> CGRect {
        let c = p(cx, cy)
        let rr = r * rect.width / 24
        return CGRect(x: c.x - rr, y: c.y - rr, width: 2 * rr, height: 2 * rr)
    }
}

